// Build a classic worker so Safari 14 can use the same tested rules and engine.
import { readFileSync, writeFileSync } from 'node:fs';
import { argv } from 'node:process';

const root = new URL('../site/activities/four-in-a-row/', import.meta.url);
const files = ['core.js', 'engine.js', 'worker-entry.js'];
const body = files.map(file => {
  const source = readFileSync(new URL(file, root), 'utf8')
    .replace(/^import [^\n]+\n/gm, '').replace(/^export /gm, '');
  if (/^\s*(import|export)\s/m.test(source)) throw new Error(`Unsupported module syntax in ${file}`);
  return `// ${file}\n${source}`;
}).join('\n');
const result = `// Generated by node scripts/build-four-in-a-row-worker.mjs. Do not edit directly.\n/* eslint-disable no-unused-vars -- Shared source exports are bundled here and linted in their source modules. */\n(() => {\n'use strict';\n${body}\n})();\n`;
const target = new URL('worker.js', root);
if (argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== result) throw new Error('Rebuild Four in a Row worker: node scripts/build-four-in-a-row-worker.mjs');
} else writeFileSync(target, result);
