CREATE TABLE public.submissions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  instance_id uuid NOT NULL
    REFERENCES public.assignment_instances(id)
    ON DELETE CASCADE,
  submitted_at timestamptz NOT NULL DEFAULT now(),
