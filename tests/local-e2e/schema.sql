  score_auto numeric,
  score_manual numeric,
  score_total numeric,
  detail jsonb,
  notes text,
  original_submission_id uuid
    REFERENCES public.submissions(id)
    ON DELETE SET NULL,
  submission_type text NOT NULL DEFAULT 'initial'
    CHECK (submission_type IN ('initial', 'resubmission')),
  source_type text NOT NULL DEFAULT 'portal'
    CHECK (source_type IN ('portal', 'google_form', 'import')),
  review_status text NOT NULL DEFAULT 'pending'
    CHECK (
      review_status IN (
        'pending',
        'in_progress',
        'reviewed',
        'finalized',
        'returned'
      )
    ),
  graded_at timestamptz,
  graded_by text,
  feedback text,
  school_year integer
);

CREATE INDEX idx_submissions_instance
  ON public.submissions(instance_id);

