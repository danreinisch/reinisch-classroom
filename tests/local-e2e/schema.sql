CREATE TABLE public.goals (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid
    REFERENCES public.students(id)
    ON DELETE CASCADE,
  code text,
  "desc" text,
  description text,
  target text,
  status text NOT NULL DEFAULT 'Open',
  version integer NOT NULL DEFAULT 1,
  active boolean NOT NULL DEFAULT true,
  replaced_by uuid
    REFERENCES public.goals(id)
    ON DELETE SET NULL,
  start_date date,

  goal_area text,
  area text,
  skill_area text,

  baseline text,
  mastery text,
  measurement_type text NOT NULL DEFAULT 'percent',
  class_context text,
  case_manager text,
  data_collector text,
  data_collector_email text,
  observation_config jsonb,
  notes text,
  addressed_in_class boolean NOT NULL DEFAULT true,
  individual_delivery boolean NOT NULL DEFAULT false,

