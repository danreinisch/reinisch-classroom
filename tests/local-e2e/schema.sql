CREATE TABLE public.app_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  role text NOT NULL
    CHECK (role IN ('student', 'teacher', 'substitute', 'admin')),

  -- Historical auth RPCs expose this as bigint. Current classroom students use
  -- UUID IDs, so local E2E deliberately leaves this nullable and unlinked.
  student_id bigint,

  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.verify_student_password(
  p_code text,
  p_password text
)
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.app_users
    WHERE username = upper(trim(p_code))
      AND role = 'student'
      AND password_hash = extensions.crypt(p_password, password_hash)
  );
$$;

CREATE OR REPLACE FUNCTION public.verify_user_password(
  p_username text,
  p_password text
)
RETURNS TABLE(
  username text,
  role text,
  student_id bigint,
  user_id bigint
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_user public.app_users%ROWTYPE;
BEGIN
  SELECT *
  INTO v_user
  FROM public.app_users
  WHERE app_users.username = p_username;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  IF v_user.password_hash =
     extensions.crypt(p_password, v_user.password_hash)
  THEN
    RETURN QUERY
    SELECT
      v_user.username,
      v_user.role,
      v_user.student_id,
      v_user.id;
  END IF;
END;
$$;

