  max_points numeric,
  teacher_note text,
  rationale text,
  ai_suggested_score numeric,
  scored_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (submission_id, assignment_item_id)
);

CREATE INDEX idx_submission_answers_submission_id
  ON public.submission_answers(submission_id);

CREATE INDEX idx_submission_answers_item_id
  ON public.submission_answers(assignment_item_id);

