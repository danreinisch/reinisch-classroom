CREATE TABLE public.goal_progress (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  goal_id uuid NOT NULL
    REFERENCES public.goals(id)
    ON DELETE CASCADE,
  student_id uuid NOT NULL
    REFERENCES public.students(id)
    ON DELETE CASCADE,
  class_id uuid
    REFERENCES public.classes(id)
    ON DELETE SET NULL,
  date date NOT NULL,
  value numeric NOT NULL
    CHECK (value >= 0 AND value <= 100),
  source text NOT NULL DEFAULT 'manual'
    CHECK (source IN ('manual', 'assignment', 'import')),
  assignment_instance_id uuid
    REFERENCES public.assignment_instances(id)
    ON DELETE SET NULL,
  collected_by text,
  school_year integer,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_goal_progress_assignment_instance
  ON public.goal_progress(assignment_instance_id);

CREATE TABLE public.goal_data_points (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  goal_id uuid NOT NULL
    REFERENCES public.goals(id)
    ON DELETE CASCADE,
  student_id uuid NOT NULL
    REFERENCES public.students(id)
    ON DELETE CASCADE,
  assignment_instance_id uuid
    REFERENCES public.assignment_instances(id)
    ON DELETE SET NULL,
  item_id bigint
    REFERENCES public.assignment_items(id)
    ON DELETE SET NULL,
  question_text text,
  choices jsonb,
  student_answer text,
  correct_answer text,
  is_correct boolean,
  score numeric,
  date date NOT NULL,
  source text NOT NULL DEFAULT 'assignment'
    CHECK (source IN ('assignment', 'manual')),
  school_year text,
  created_at timestamptz NOT NULL DEFAULT now()
);

