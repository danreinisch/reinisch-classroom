CREATE TABLE public.assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text,
  section text DEFAULT 'language-arts',
  due_date date,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),

  -- Runtime accepts values such as html/txt without requiring historical enum.
  type text NOT NULL DEFAULT 'html',

  series text,
  page text,
  hero text,
  meta jsonb DEFAULT '{}'::jsonb,
  created_by text,
  class_id uuid
    REFERENCES public.classes(id)
    ON DELETE SET NULL,

  first_submission_at timestamptz,
  version_locked boolean NOT NULL DEFAULT false,
  source_type text NOT NULL DEFAULT 'portal'
    CHECK (source_type IN ('portal', 'google_form', 'import')),
  school_year integer,
  finalized_at timestamptz
);

CREATE TABLE public.assignment_instances (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id bigint NOT NULL
    REFERENCES public.assignments(id)
    ON DELETE CASCADE,
  student_id uuid NOT NULL
    REFERENCES public.students(id)
    ON DELETE CASCADE,
  assigned_at date NOT NULL DEFAULT CURRENT_DATE,
  due_at date,
  status text NOT NULL DEFAULT 'Assigned',
  settings jsonb NOT NULL DEFAULT '{}'::jsonb,
  resubmission_count integer NOT NULL DEFAULT 0,
  school_year integer,
  UNIQUE (assignment_id, student_id)
);

CREATE TABLE public.assignment_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id bigint NOT NULL
    REFERENCES public.assignments(id)
    ON DELETE CASCADE,
  item_ref text NOT NULL,
  answer_type text NOT NULL
    CHECK (
      answer_type IN (
        'mcq',
        'multi',
        'boolean',
        'constructed',
        'written_response'
      )
    ),
  points numeric NOT NULL DEFAULT 1
    CHECK (points >= 0),
  meta jsonb NOT NULL DEFAULT '{}'::jsonb,
  goal_codes text[] NOT NULL DEFAULT ARRAY[]::text[],
  dese_codes text[] NOT NULL DEFAULT ARRAY[]::text[],
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (assignment_id, item_ref)
);

-- Current runtime joins this bigint item_id to assignment_items.id.
CREATE TABLE public.assignment_item_mappings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id bigint NOT NULL
    REFERENCES public.assignment_items(id)
    ON DELETE CASCADE,
  dese_codes text[] NOT NULL DEFAULT ARRAY[]::text[],
  goal_codes text[] NOT NULL DEFAULT ARRAY[]::text[],
  weight numeric NOT NULL DEFAULT 1.0
    CHECK (weight >= 0 AND weight <= 1),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (item_id)
);

