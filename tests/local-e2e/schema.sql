CREATE TABLE public.teacher_drafts (
  id text PRIMARY KEY,
  teacher text NOT NULL DEFAULT 'default',
  title text NOT NULL,
  class_name text,
  release_at timestamptz,
  due_at timestamptz,
  notes text,
  assignment jsonb NOT NULL DEFAULT '{}'::jsonb,
  mapping jsonb NOT NULL DEFAULT '{}'::jsonb,
  auto_release boolean NOT NULL DEFAULT false,
  issued_at timestamptz,
  auto_release_status text NOT NULL DEFAULT 'pending'
    CHECK (
      auto_release_status IN (
        'pending',
        'issued',
        'errored',
        'disabled'
      )
    ),
  auto_release_error text,
  auto_release_attempted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_teacher_drafts_teacher
  ON public.teacher_drafts(teacher);

CREATE INDEX idx_teacher_drafts_updated
  ON public.teacher_drafts(updated_at DESC);

CREATE INDEX idx_teacher_drafts_auto_release_due
  ON public.teacher_drafts(release_at)
  WHERE
    auto_release = true
    AND auto_release_status = 'pending'
    AND issued_at IS NULL;

